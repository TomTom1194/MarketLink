IF OBJECT_ID('Order_Disputes', 'U') IS NULL
BEGIN
    CREATE TABLE Order_Disputes (
        dispute_id          INT IDENTITY(1,1) PRIMARY KEY,
        order_id            INT NOT NULL UNIQUE REFERENCES Orders(order_id),
        reported_by         NVARCHAR(20) NOT NULL CHECK (reported_by IN ('customer', 'farmer')),
        customer_reason     NVARCHAR(500) NULL,
        customer_reason_at  DATETIME2 NULL,
        farmer_reason       NVARCHAR(500) NULL,
        farmer_reason_at    DATETIME2 NULL,
        status              NVARCHAR(20) NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'resolved')),
        at_fault            NVARCHAR(20) NULL CHECK (at_fault IN ('customer', 'farmer', 'none')),
        admin_note          NVARCHAR(500) NULL,
        resolved_by         INT NULL REFERENCES Users(user_id),
        resolved_at         DATETIME2 NULL,
        created_at          DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
        CHECK (status <> 'resolved' OR at_fault IS NOT NULL)
    );
    PRINT 'Table Order_Disputes created.';
END
ELSE
    PRINT 'Table Order_Disputes already exists.';
GO

